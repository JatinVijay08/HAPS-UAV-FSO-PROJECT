clear;
clc;
close all;

%% =========================================================
% EXPERIMENT 16
% ADAPTIVE THRESHOLD JAMMER MITIGATION
%
% Compare:
%
%   1. Normal fixed threshold
%   2. Jammed signal + fixed threshold
%   3. Jammed signal + adaptive threshold
%
% Tested for:
%
%   Constant jammer
%   Random jammer
%
%% =========================================================


%% =========================================================
% PATH
%% =========================================================

projectRoot = ...
    fileparts(fileparts(mfilename('fullpath')));

addpath(genpath(projectRoot));


%% =========================================================
% PARAMETERS
%% =========================================================

params = defaultParameters();

params.Nbits = 10000;

params.rngSeed = 42;

params.enableSaturation = true;


%% =========================================================
% ADAPTATION STRENGTH
%% =========================================================

gamma = 1.0;


%% =========================================================
% GENERATE CLEAN BASELINE
%% =========================================================

params.enableJammer = false;

resultsBase = ...
    runBaseline(params);


%% =========================================================
% BASELINE STATISTICS
%% =========================================================

baselineMeanCurrent = ...
    mean(resultsBase.rxCurrent);


nominalThreshold = ...
    resultsBase.threshold;


fprintf('\n');
fprintf('============================================\n');
fprintf(' EXPERIMENT 16 - ADAPTIVE THRESHOLD\n');
fprintf('============================================\n\n');

fprintf('Baseline Mean Current = %.6f A\n', ...
    baselineMeanCurrent);

fprintf('Nominal Threshold     = %.6f A\n', ...
    nominalThreshold);

fprintf('Adaptation Strength   = %.2f\n\n', ...
    gamma);


%% =========================================================
% CONSTANT JAMMER TEST
%% =========================================================

constantPowers = [ ...
    0.05 ...
    0.10 ...
    0.15 ...
    0.20 ...
    0.25 ...
    0.30 ...
    0.40];


constantBERFixed = ...
    zeros(size(constantPowers));

constantBERAdaptive = ...
    zeros(size(constantPowers));

constantThresholds = ...
    zeros(size(constantPowers));


fprintf('============================================\n');
fprintf(' CONSTANT JAMMER MITIGATION\n');
fprintf('============================================\n');


for k = 1:length(constantPowers)

    %% -----------------------------------------------------
    % Generate constant jammer
    %% -----------------------------------------------------

    jammerSignal = ...
        jammerModel( ...
            constantPowers(k), ...
            params.Nbits, ...
            params.samplesPerBit, ...
            true);


    %% -----------------------------------------------------
    % Add jammer
    %% -----------------------------------------------------

    rxOpticalSignal = ...
        resultsBase.rxOpticalSignal + ...
        jammerSignal;


    %% -----------------------------------------------------
    % Receiver current
    %% -----------------------------------------------------

    [~, BERFixed, rxCurrent, ~, ~] = ...
        receiverModel( ...
            rxOpticalSignal, ...
            resultsBase.bits, ...
            params.Pt, ...
            resultsBase.H_total, ...
            params.R, ...
            params.samplesPerBit, ...
            resultsBase.receiverNoise, ...
            params.enableSaturation);


    %% -----------------------------------------------------
    % Adaptive threshold
    %% -----------------------------------------------------

    [~, BERAdaptive, adaptiveThreshold, estimatedJammer] = ...
        adaptiveThresholdReceiver( ...
            rxCurrent, ...
            resultsBase.bits, ...
            nominalThreshold, ...
            baselineMeanCurrent, ...
            params.samplesPerBit, ...
            gamma);


    constantBERFixed(k) = BERFixed;

    constantBERAdaptive(k) = BERAdaptive;

    constantThresholds(k) = adaptiveThreshold;


    fprintf( ...
        'Pj = %.3f W | Fixed BER = %.4f | Adaptive BER = %.4f | Estimated J = %.4f A | Threshold = %.4f A\n', ...
        constantPowers(k), ...
        BERFixed, ...
        BERAdaptive, ...
        estimatedJammer, ...
        adaptiveThreshold);

end


%% =========================================================
% RANDOM JAMMER TEST
%% =========================================================

randomPeakPower = 0.40;

activityProbabilities = [ ...
    0.10 ...
    0.20 ...
    0.30 ...
    0.40 ...
    0.50 ...
    0.60 ...
    0.70 ...
    0.80 ...
    0.90 ...
    1.00];


randomBERFixed = ...
    zeros(size(activityProbabilities));

randomBERAdaptive = ...
    zeros(size(activityProbabilities));

randomThresholds = ...
    zeros(size(activityProbabilities));


fprintf('\n');
fprintf('============================================\n');
fprintf(' RANDOM JAMMER MITIGATION\n');
fprintf('============================================\n');


for k = 1:length(activityProbabilities)

    %% -----------------------------------------------------
    % Reuse same baseline realization
    %% -----------------------------------------------------

    rng(2000 + k);


    %% -----------------------------------------------------
    % Generate random jammer
    %% -----------------------------------------------------

    [jammerSignal, jammerBits] = ...
        randomJammerModel( ...
            randomPeakPower, ...
            params.Nbits, ...
            params.samplesPerBit, ...
            true, ...
            activityProbabilities(k));


    %% -----------------------------------------------------
    % Add jammer
    %% -----------------------------------------------------

    rxOpticalSignal = ...
        resultsBase.rxOpticalSignal + ...
        jammerSignal;


    %% -----------------------------------------------------
    % Receiver
    %% -----------------------------------------------------

    [~, BERFixed, rxCurrent, ~, ~] = ...
        receiverModel( ...
            rxOpticalSignal, ...
            resultsBase.bits, ...
            params.Pt, ...
            resultsBase.H_total, ...
            params.R, ...
            params.samplesPerBit, ...
            resultsBase.receiverNoise, ...
            params.enableSaturation);


    %% -----------------------------------------------------
    % Adaptive threshold
    %% -----------------------------------------------------

    [~, BERAdaptive, adaptiveThreshold, estimatedJammer] = ...
        adaptiveThresholdReceiver( ...
            rxCurrent, ...
            resultsBase.bits, ...
            nominalThreshold, ...
            baselineMeanCurrent, ...
            params.samplesPerBit, ...
            gamma);


    randomBERFixed(k) = ...
        BERFixed;

    randomBERAdaptive(k) = ...
        BERAdaptive;

    randomThresholds(k) = ...
        adaptiveThreshold;


    actualActivity = ...
        mean(jammerBits);


    fprintf( ...
        'Activity = %.2f | Actual = %.3f | Fixed BER = %.4f | Adaptive BER = %.4f | Estimated J = %.4f A | Threshold = %.4f A\n', ...
        activityProbabilities(k), ...
        actualActivity, ...
        BERFixed, ...
        BERAdaptive, ...
        estimatedJammer, ...
        adaptiveThreshold);

end


%% =========================================================
% GRAPH 1
% CONSTANT JAMMER
%% =========================================================

figure;

plot( ...
    constantPowers, ...
    constantBERFixed, ...
    '-o', ...
    'LineWidth', 1.5);

hold on;

plot( ...
    constantPowers, ...
    constantBERAdaptive, ...
    '-s', ...
    'LineWidth', 1.5);

grid on;

xlabel('Constant Jammer Power (W)');

ylabel('Bit Error Rate (BER)');

title('Experiment 16: Adaptive Threshold — Constant Jammer');

legend( ...
    'Fixed Threshold', ...
    'Adaptive Threshold', ...
    'Location', ...
    'best');


%% =========================================================
% GRAPH 2
% RANDOM JAMMER
%% =========================================================

figure;

plot( ...
    activityProbabilities, ...
    randomBERFixed, ...
    '-o', ...
    'LineWidth', 1.5);

hold on;

plot( ...
    activityProbabilities, ...
    randomBERAdaptive, ...
    '-s', ...
    'LineWidth', 1.5);

grid on;

xlabel('Jammer Activity Probability');

ylabel('Bit Error Rate (BER)');

title('Experiment 16: Adaptive Threshold — Random Jammer');

legend( ...
    'Fixed Threshold', ...
    'Adaptive Threshold', ...
    'Location', ...
    'best');


%% =========================================================
% GRAPH 3
% ADAPTIVE THRESHOLD
%% =========================================================

figure;

plot( ...
    constantPowers, ...
    constantThresholds, ...
    '-o', ...
    'LineWidth', 1.5);

hold on;

yline( ...
    nominalThreshold, ...
    '--', ...
    'Nominal Threshold');

grid on;

xlabel('Constant Jammer Power (W)');

ylabel('Decision Threshold (A)');

title('Adaptive Threshold vs Constant Jammer Power');

legend( ...
    'Adaptive Threshold', ...
    'Nominal Threshold', ...
    'Location', ...
    'best');


